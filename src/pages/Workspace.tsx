import { useState, useEffect, useRef, useCallback } from 'react';
import { useLocation } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import {
  Sparkles, Send, Square, RotateCcw, Settings, ChevronRight,
  Terminal, Monitor, FileText, Code2, Play, CheckCircle2,
  XCircle, Clock, Cpu, Zap, Download, FolderOpen, MessageSquare,
  ListTodo, Eye, AlertTriangle
} from 'lucide-react';
import { useI18n } from '../i18n';

/* ─── Types ─── */
interface ThreadMessage {
  id: string;
  type: 'user' | 'thought' | 'tool' | 'console' | 'file' | 'system';
  content: string;
  tool?: string;
  timestamp: number;
}

interface PlanStep {
  id: string;
  title: string;
  status: 'pending' | 'running' | 'done' | 'error';
}

interface FileEntry {
  name: string;
  path: string;
  content: string;
  type: 'file' | 'folder';
}

type RunStatus = 'idle' | 'planning' | 'running' | 'done' | 'error';

/* ─── Simulated Agent Engine ─── */
function simulateAgentRun(prompt: string, onEvent: (event: any) => void) {
  const steps: PlanStep[] = [
    { id: '1', title: 'Analyze requirements', status: 'pending' },
    { id: '2', title: 'Design architecture', status: 'pending' },
    { id: '3', title: 'Generate code', status: 'pending' },
    { id: '4', title: 'Test & validate', status: 'pending' },
    { id: '5', title: 'Package artifact', status: 'pending' },
  ];

  const messages: ThreadMessage[] = [
    { id: 'm1', type: 'thought', content: `Analyzing prompt: "${prompt}". Breaking down into actionable steps...`, timestamp: Date.now() },
    { id: 'm2', type: 'tool', content: 'Searching for best practices and patterns...', tool: 'web_search', timestamp: Date.now() + 1000 },
    { id: 'm3', type: 'console', content: '$ mkdir -p /project/src && cd /project', timestamp: Date.now() + 2000 },
    { id: 'm4', type: 'file', content: 'Creating index.html with responsive layout...', timestamp: Date.now() + 3000 },
    { id: 'm5', type: 'tool', content: 'Generated 3 files: index.html, styles.css, app.js', tool: 'write_file', timestamp: Date.now() + 4000 },
    { id: 'm6', type: 'console', content: '$ npm run build\n✓ Build completed in 1.2s\n✓ Output: dist/index.html (12.4KB)', timestamp: Date.now() + 5000 },
    { id: 'm7', type: 'thought', content: 'All steps completed successfully. Artifact is ready for preview.', timestamp: Date.now() + 6000 },
  ];

  const files: FileEntry[] = [
    { name: 'src', path: '/src', content: '', type: 'folder' },
    { name: 'index.html', path: '/index.html', content: '<!DOCTYPE html>\n<html>\n<head><title>Generated App</title></head>\n<body>\n  <div id="app">\n    <h1>Hello from RS-BUILDER</h1>\n    <p>This artifact was generated by the AI agent.</p>\n  </div>\n</body>\n</html>', type: 'file' },
    { name: 'styles.css', path: '/styles.css', content: '* { margin: 0; padding: 0; box-sizing: border-box; }\nbody { font-family: system-ui; padding: 2rem; }\nh1 { color: #4f46e5; margin-bottom: 1rem; }', type: 'file' },
    { name: 'app.js', path: '/src/app.js', content: 'console.log("RS-BUILDER artifact loaded");\ndocument.addEventListener("DOMContentLoaded", () => {\n  console.log("App initialized");\n});', type: 'file' },
  ];

  let cancelled = false;
  let stepIndex = 0;
  let msgIndex = 0;

  const run = async () => {
    // Plan
    onEvent({ type: 'plan', steps });
    await delay(800);

    // Execute steps
    for (let i = 0; i < steps.length && !cancelled; i++) {
      stepIndex = i;
      onEvent({ type: 'step_start', stepId: steps[i].id });
      await delay(600 + Math.random() * 800);

      // Emit messages for this step
      const msgsForStep = messages.filter((_, idx) => Math.floor(idx / 2) === i || (i === 0 && idx < 2));
      for (const msg of msgsForStep) {
        if (cancelled) return;
        onEvent({ type: 'message', message: msg });
        await delay(400 + Math.random() * 400);
      }

      onEvent({ type: 'step_done', stepId: steps[i].id });
      onEvent({ type: 'progress', current: i + 1, total: steps.length });
    }

    if (!cancelled) {
      // Files
      onEvent({ type: 'files', files });
      await delay(500);

      // Artifact
      const artifactHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Generated Artifact</title>
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    body { font-family: system-ui, sans-serif; min-height: 100vh; display: flex; align-items: center; justify-content: center; background: linear-gradient(135deg, #1e1b4b, #312e81); color: white; }
    .container { text-align: center; padding: 2rem; }
    h1 { font-size: 2.5rem; margin-bottom: 1rem; background: linear-gradient(to right, #818cf8, #06b6d4); -webkit-background-clip: text; -webkit-text-fill-color: transparent; }
    p { color: #94a3b8; font-size: 1.1rem; max-width: 400px; }
    .badge { display: inline-block; margin-top: 1.5rem; padding: 0.5rem 1rem; border-radius: 9999px; background: rgba(99,102,241,0.2); border: 1px solid rgba(99,102,241,0.3); font-size: 0.875rem; color: #a5b4fc; }
  </style>
</head>
<body>
  <div class="container">
    <h1>✨ Artifact Ready</h1>
    <p>This is a live preview of the generated artifact based on your prompt.</p>
    <div class="badge">Built with RS-BUILDER</div>
  </div>
</body>
</html>`;
      onEvent({ type: 'artifact', html: artifactHtml });
      await delay(300);
      onEvent({ type: 'done' });
    }
  };

  const cancel = () => { cancelled = true; };

  return { run, cancel };
}

function delay(ms: number) {
  return new Promise(r => setTimeout(r, ms));
}

/* ─── Workspace Component ─── */
export default function Workspace() {
  const { t } = useI18n();
  const location = useLocation();
  const initialPrompt = (location.state as any)?.initialPrompt || '';

  const [prompt, setPrompt] = useState(initialPrompt);
  const [status, setStatus] = useState<RunStatus>('idle');
  const [messages, setMessages] = useState<ThreadMessage[]>([]);
  const [plan, setPlan] = useState<PlanStep[]>([]);
  const [files, setFiles] = useState<FileEntry[]>([]);
  const [artifact, setArtifact] = useState<string>('');
  const [activeTab, setActiveTab] = useState<'preview' | 'files' | 'console'>('preview');
  const [progress, setProgress] = useState({ current: 0, total: 0 });
  const [consoleOutput, setConsoleOutput] = useState<string[]>([]);
  const [showSettings, setShowSettings] = useState(false);
  const cancelRef = useRef<(() => void) | null>(null);
  const threadRef = useRef<HTMLDivElement>(null);

  const handleEvent = useCallback((event: any) => {
    switch (event.type) {
      case 'plan':
        setPlan(event.steps);
        setStatus('running');
        break;
      case 'step_start':
        setPlan(prev => prev.map(s => s.id === event.stepId ? { ...s, status: 'running' } : s));
        break;
      case 'step_done':
        setPlan(prev => prev.map(s => s.id === event.stepId ? { ...s, status: 'done' } : s));
        break;
      case 'message':
        setMessages(prev => [...prev, event.message]);
        if (event.message.type === 'console') {
          setConsoleOutput(prev => [...prev, event.message.content]);
        }
        break;
      case 'progress':
        setProgress(event);
        break;
      case 'files':
        setFiles(event.files);
        break;
      case 'artifact':
        setArtifact(event.html);
        break;
      case 'done':
        setStatus('done');
        break;
    }
  }, []);

  const handleRun = () => {
    if (!prompt.trim()) return;
    setStatus('planning');
    setMessages([]);
    setPlan([]);
    setFiles([]);
    setArtifact('');
    setConsoleOutput([]);
    setProgress({ current: 0, total: 0 });

    const userMsg: ThreadMessage = {
      id: 'user-' + Date.now(),
      type: 'user',
      content: prompt,
      timestamp: Date.now(),
    };
    setMessages([userMsg]);

    const { run, cancel } = simulateAgentRun(prompt, handleEvent);
    cancelRef.current = cancel;
    run();
  };

  const handleStop = () => {
    if (cancelRef.current) {
      cancelRef.current();
      setStatus('idle');
    }
  };

  const handleReset = () => {
    handleStop();
    setPrompt('');
    setMessages([]);
    setPlan([]);
    setFiles([]);
    setArtifact('');
    setConsoleOutput([]);
    setProgress({ current: 0, total: 0 });
    setStatus('idle');
  };

  useEffect(() => {
    if (threadRef.current) {
      threadRef.current.scrollTop = threadRef.current.scrollHeight;
    }
  }, [messages]);

  const tabs = [
    { id: 'preview' as const, label: t.workspace.preview, icon: Eye },
    { id: 'files' as const, label: t.workspace.files, icon: FolderOpen },
    { id: 'console' as const, label: t.workspace.console, icon: Terminal },
  ];

  return (
    <main className="pt-16 h-screen flex flex-col" style={{ backgroundColor: 'var(--bg)' }}>
      {/* Toolbar */}
      <div className="flex items-center justify-between px-4 py-2 border-b" style={{ borderColor: 'var(--border)', backgroundColor: 'var(--bg-secondary)' }}>
        <div className="flex items-center gap-3">
          <div className="flex items-center gap-2">
            <div className={`w-2 h-2 rounded-full ${status === 'running' ? 'bg-green-500 animate-pulse' : status === 'done' ? 'bg-accent-500' : status === 'error' ? 'bg-red-500' : 'bg-surface-400'}`} />
            <span className="text-sm font-medium" style={{ color: 'var(--text)' }}>
              {status === 'idle' ? 'Ready' : status === 'planning' ? t.workspace.thinking : status === 'running' ? t.workspace.running : status === 'done' ? t.workspace.done : t.workspace.error}
            </span>
          </div>
          {progress.total > 0 && (
            <span className="text-xs px-2 py-0.5 rounded-full bg-brand-500/10 text-brand-500">
              {progress.current}/{progress.total} {t.workspace.steps}
            </span>
          )}
        </div>
        <div className="flex items-center gap-2">
          {(status === 'running' || status === 'planning') && (
            <button onClick={handleStop} className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-sm font-medium bg-red-500/10 text-red-500 hover:bg-red-500/20 transition-colors">
              <Square size={14} /> {t.workspace.stop}
            </button>
          )}
          <button onClick={handleReset} className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-sm font-medium transition-colors hover:bg-brand-500/10" style={{ color: 'var(--text-muted)' }}>
            <RotateCcw size={14} /> {t.workspace.reset}
          </button>
          <button onClick={() => setShowSettings(!showSettings)} className="p-1.5 rounded-lg transition-colors hover:bg-brand-500/10" style={{ color: 'var(--text-muted)' }}>
            <Settings size={16} />
          </button>
        </div>
      </div>

      {/* Main content */}
      <div className="flex-1 flex overflow-hidden">
        {/* Left panel - Thread & Plan */}
        <div className="w-80 border-r flex flex-col" style={{ borderColor: 'var(--border)' }}>
          {/* Plan */}
          {plan.length > 0 && (
            <div className="p-3 border-b" style={{ borderColor: 'var(--border)' }}>
              <div className="flex items-center gap-2 mb-2">
                <ListTodo size={14} className="text-brand-500" />
                <span className="text-xs font-semibold uppercase tracking-wider" style={{ color: 'var(--text-muted)' }}>{t.workspace.plan}</span>
              </div>
              <div className="space-y-1.5">
                {plan.map(step => (
                  <div key={step.id} className="flex items-center gap-2 text-sm">
                    {step.status === 'done' ? (
                      <CheckCircle2 size={14} className="text-accent-500 shrink-0" />
                    ) : step.status === 'running' ? (
                      <div className="w-3.5 h-3.5 border-2 border-brand-500 border-t-transparent rounded-full animate-spin shrink-0" />
                    ) : (
                      <div className="w-3.5 h-3.5 rounded-full border-2 shrink-0" style={{ borderColor: 'var(--border)' }} />
                    )}
                    <span style={{ color: step.status === 'done' ? 'var(--text)' : step.status === 'running' ? 'var(--text)' : 'var(--text-muted)' }}>
                      {step.title}
                    </span>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Thread */}
          <div className="flex-1 overflow-hidden flex flex-col">
            <div className="flex items-center gap-2 px-3 pt-3 pb-2">
              <MessageSquare size={14} className="text-brand-500" />
              <span className="text-xs font-semibold uppercase tracking-wider" style={{ color: 'var(--text-muted)' }}>{t.workspace.thread}</span>
            </div>
            <div ref={threadRef} className="flex-1 overflow-y-auto px-3 pb-3 space-y-2">
              {messages.length === 0 && status === 'idle' && (
                <div className="text-center py-8">
                  <Sparkles size={24} className="mx-auto mb-2 text-brand-500/50" />
                  <p className="text-xs" style={{ color: 'var(--text-muted)' }}>
                    Enter a prompt to start
                  </p>
                </div>
              )}
              <AnimatePresence>
                {messages.map(msg => (
                  <motion.div
                    key={msg.id}
                    initial={{ opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    className={`p-2.5 rounded-lg text-xs ${
                      msg.type === 'user' ? 'bg-brand-500/10 border border-brand-500/20' :
                      msg.type === 'thought' ? 'bg-purple-500/5 border border-purple-500/10' :
                      msg.type === 'tool' ? 'bg-orange-500/5 border border-orange-500/10' :
                      msg.type === 'console' ? 'bg-surface-800/50 border border-surface-700/50 font-mono' :
                      msg.type === 'file' ? 'bg-green-500/5 border border-green-500/10' :
                      'border'
                    }`}
                    style={{ borderColor: msg.type === 'system' ? 'var(--border)' : undefined }}
                  >
                    {msg.type === 'tool' && (
                      <span className="inline-flex items-center gap-1 text-orange-400 font-medium mb-1">
                        <Zap size={10} /> {msg.tool}
                      </span>
                    )}
                    <p style={{ color: msg.type === 'console' ? '#a5b4fc' : 'var(--text-secondary)' }}>
                      {msg.content}
                    </p>
                  </motion.div>
                ))}
              </AnimatePresence>
            </div>
          </div>

          {/* Input */}
          <div className="p-3 border-t" style={{ borderColor: 'var(--border)' }}>
            <div className="flex items-center gap-2">
              <input
                type="text"
                value={prompt}
                onChange={e => setPrompt(e.target.value)}
                onKeyDown={e => e.key === 'Enter' && !e.shiftKey && handleRun()}
                placeholder={t.hero.placeholder}
                disabled={status === 'running' || status === 'planning'}
                className="flex-1 px-3 py-2 rounded-lg text-sm border outline-none focus:ring-2 focus:ring-brand-500/50 transition-all disabled:opacity-50"
                style={{ borderColor: 'var(--border)', backgroundColor: 'var(--bg-secondary)', color: 'var(--text)' }}
              />
              <button
                onClick={handleRun}
                disabled={!prompt.trim() || status === 'running' || status === 'planning'}
                className="p-2 rounded-lg bg-brand-600 text-white hover:bg-brand-700 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
              >
                <Send size={16} />
              </button>
            </div>
          </div>
        </div>

        {/* Right panel - Tabs */}
        <div className="flex-1 flex flex-col overflow-hidden">
          {/* Tab bar */}
          <div className="flex items-center border-b px-2" style={{ borderColor: 'var(--border)' }}>
            {tabs.map(tab => (
              <button
                key={tab.id}
                onClick={() => setActiveTab(tab.id)}
                className={`flex items-center gap-1.5 px-4 py-2.5 text-sm font-medium border-b-2 transition-colors ${
                  activeTab === tab.id ? 'border-brand-500 text-brand-500' : 'border-transparent hover:text-brand-400'
                }`}
                style={{ color: activeTab === tab.id ? undefined : 'var(--text-muted)' }}
              >
                <tab.icon size={14} />
                {tab.label}
              </button>
            ))}
          </div>

          {/* Tab content */}
          <div className="flex-1 overflow-hidden">
            {/* Preview */}
            {activeTab === 'preview' && (
              <div className="h-full p-4">
                {artifact ? (
                  <div className="h-full rounded-xl border overflow-hidden" style={{ borderColor: 'var(--border)' }}>
                    <iframe
                      srcDoc={artifact}
                      className="w-full h-full"
                      sandbox="allow-scripts"
                      title="Artifact Preview"
                    />
                  </div>
                ) : (
                  <div className="h-full flex items-center justify-center rounded-xl border" style={{ borderColor: 'var(--border)', backgroundColor: 'var(--bg-secondary)' }}>
                    <div className="text-center">
                      <Monitor size={48} className="mx-auto mb-4 text-brand-500/30" />
                      <p className="text-sm font-medium mb-1" style={{ color: 'var(--text-muted)' }}>
                        {status === 'running' ? t.workspace.running : 'No artifact yet'}
                      </p>
                      <p className="text-xs" style={{ color: 'var(--text-muted)' }}>
                        {status === 'idle' ? 'Run the agent to generate a preview' : 'Preview will appear here...'}
                      </p>
                    </div>
                  </div>
                )}
              </div>
            )}

            {/* Files */}
            {activeTab === 'files' && (
              <div className="h-full p-4 overflow-y-auto">
                {files.length > 0 ? (
                  <div className="space-y-2">
                    <div className="flex items-center justify-between mb-4">
                      <span className="text-sm font-medium" style={{ color: 'var(--text)' }}>
                        {files.length} files
                      </span>
                      <button className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium border transition-colors hover:border-brand-500"
                        style={{ borderColor: 'var(--border)', color: 'var(--text-secondary)' }}
                      >
                        <Download size={12} /> {t.workspace.downloadAll}
                      </button>
                    </div>
                    {files.map((file, i) => (
                      <div key={i} className="flex items-center gap-3 p-3 rounded-lg border transition-colors hover:border-brand-500/50"
                        style={{ borderColor: 'var(--border)', backgroundColor: 'var(--card)' }}
                      >
                        {file.type === 'folder' ? (
                          <FolderOpen size={16} className="text-brand-500" />
                        ) : (
                          <FileText size={16} className="text-accent-500" />
                        )}
                        <div className="flex-1">
                          <p className="text-sm font-medium font-mono" style={{ color: 'var(--text)' }}>{file.name}</p>
                          <p className="text-xs" style={{ color: 'var(--text-muted)' }}>{file.path}</p>
                        </div>
                        {file.type === 'file' && (
                          <button className="p-1.5 rounded hover:bg-brand-500/10 transition-colors" style={{ color: 'var(--text-muted)' }}>
                            <Download size={14} />
                          </button>
                        )}
                      </div>
                    ))}
                  </div>
                ) : (
                  <div className="h-full flex items-center justify-center">
                    <div className="text-center">
                      <FolderOpen size={48} className="mx-auto mb-4 text-brand-500/30" />
                      <p className="text-sm" style={{ color: 'var(--text-muted)' }}>No files yet</p>
                    </div>
                  </div>
                )}
              </div>
            )}

            {/* Console */}
            {activeTab === 'console' && (
              <div className="h-full p-4">
                <div className="h-full rounded-xl border overflow-hidden" style={{ borderColor: 'var(--border)', backgroundColor: '#0d1117' }}>
                  <div className="flex items-center gap-2 px-3 py-2 border-b" style={{ borderColor: '#21262d' }}>
                    <Terminal size={14} className="text-green-400" />
                    <span className="text-xs font-mono text-green-400">console</span>
                  </div>
                  <div className="p-3 overflow-y-auto h-[calc(100%-36px)] font-mono text-xs space-y-1">
                    {consoleOutput.length === 0 ? (
                      <p className="text-gray-500">$ Waiting for output...</p>
                    ) : (
                      consoleOutput.map((line, i) => (
                        <p key={i} className="text-gray-300 whitespace-pre-wrap">{line}</p>
                      ))
                    )}
                  </div>
                </div>
              </div>
            )}
          </div>
        </div>
      </div>

      {/* Settings modal */}
      <AnimatePresence>
        {showSettings && (
          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-sm"
            onClick={() => setShowSettings(false)}
          >
            <motion.div
              initial={{ scale: 0.95, opacity: 0 }}
              animate={{ scale: 1, opacity: 1 }}
              exit={{ scale: 0.95, opacity: 0 }}
              className="w-full max-w-md rounded-2xl border p-6"
              style={{ backgroundColor: 'var(--card)', borderColor: 'var(--border)' }}
              onClick={e => e.stopPropagation()}
            >
              <h3 className="text-lg font-bold mb-4" style={{ color: 'var(--text)' }}>{t.workspace.settings}</h3>
              <div className="space-y-4">
                <div>
                  <label className="text-sm font-medium block mb-1" style={{ color: 'var(--text-secondary)' }}>API URL</label>
                  <input
                    type="text"
                    defaultValue={import.meta.env.VITE_AGENT_API_URL || ''}
                    placeholder="http://localhost:8787"
                    className="w-full px-3 py-2 rounded-lg border text-sm outline-none focus:ring-2 focus:ring-brand-500/50"
                    style={{ borderColor: 'var(--border)', backgroundColor: 'var(--bg-secondary)', color: 'var(--text)' }}
                  />
                </div>
                <div>
                  <label className="text-sm font-medium block mb-1" style={{ color: 'var(--text-secondary)' }}>Provider API Key (optional)</label>
                  <input
                    type="password"
                    placeholder="sk-..."
                    className="w-full px-3 py-2 rounded-lg border text-sm outline-none focus:ring-2 focus:ring-brand-500/50"
                    style={{ borderColor: 'var(--border)', backgroundColor: 'var(--bg-secondary)', color: 'var(--text)' }}
                  />
                </div>
                <div className="flex items-center justify-between p-3 rounded-lg border" style={{ borderColor: 'var(--border)' }}>
                  <div>
                    <p className="text-sm font-medium" style={{ color: 'var(--text)' }}>Sandbox Mode</p>
                    <p className="text-xs" style={{ color: 'var(--text-muted)' }}>Real execution environment</p>
                  </div>
                  <div className="flex items-center gap-1.5 px-2 py-1 rounded bg-accent-500/10 text-accent-500 text-xs font-medium">
                    <Cpu size={12} /> Real
                  </div>
                </div>
              </div>
              <button
                onClick={() => setShowSettings(false)}
                className="w-full mt-4 py-2.5 rounded-xl bg-brand-600 text-white font-medium hover:bg-brand-700 transition-colors"
              >
                {t.common.save}
              </button>
            </motion.div>
          </motion.div>
        )}
      </AnimatePresence>
    </main>
  );
}
